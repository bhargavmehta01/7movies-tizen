'use strict';
const { JSDOM } = require('jsdom');
const fs = require('fs');
const assert = require('node:assert/strict');
const script = fs.readFileSync(require('path').join(__dirname, 'adblock.js'), 'utf8');
function page(url, html) {
  const dom = new JSDOM(html || '<body></body>', { url, runScripts: 'outside-only' });
  const w = dom.window;
  w.fetch = function (url) { return Promise.resolve({ original: true, url }); };
  w.eval(script);
  w.document.dispatchEvent(new w.Event('DOMContentLoaded'));
  return dom;
}
(async function () {
  const dom = page('https://7movies.ac', '<body><div data-ad-slot="banner">Ad</div><video id="player"></video><div class="overlay">Player controls</div><a id="movie" href="/movie/1">Movie</a><a id="popup" href="https://example.com" target="_blank">Popup</a></body>');
  const w = dom.window;
  assert.equal(w.sessionStorage.getItem('cinrift_ad_free'), 'true');
  assert.equal(w.open('https://example.com'), null);
  assert.equal(w.document.querySelector('[data-ad-slot]'), null);
  assert.ok(w.document.getElementById('player'));
  assert.ok(w.document.querySelector('.overlay'));
  const popup = new w.MouseEvent('click', { bubbles: true, cancelable: true });
  w.document.getElementById('popup').dispatchEvent(popup);
  assert.ok(popup.defaultPrevented);
  // Keep the test from actually navigating after verifying our listener.
  let ordinaryPrevented;
  w.document.getElementById('movie').addEventListener('click', e => { ordinaryPrevented=e.defaultPrevented; e.preventDefault(); });
  w.document.getElementById('movie').dispatchEvent(new w.MouseEvent('click', { bubbles: true, cancelable: true }));
  assert.equal(ordinaryPrevented, false);
  await assert.rejects(w.fetch('https://sub.doubleclick.net/ad'));
  assert.equal((await w.fetch('https://doubleclick.net.example.org/video')).original, true);
  assert.equal((await w.fetch('https://7movies.ac/api/catalog')).original, true);
  assert.throws(() => new w.XMLHttpRequest().open('GET', 'https://popads.net/a'));
  const s = w.document.createElement('script');
  s.src = 'https://popcash.net/ad.js';
  assert.equal(s.getAttribute('src'), null);
  s.setAttribute('src', 'https://popads.net/ad.js');
  assert.equal(s.getAttribute('src'), null);
  s.src = '/_next/app.js';
  assert.equal(s.getAttribute('src'), '/_next/app.js');
  const img = w.document.createElement('img');
  img.src = 'https://image.tmdb.org/t/p/w500/poster.jpg';
  assert.ok(img.src.includes('image.tmdb.org'));
  const state = w.__sevenMoviesGuard;
  w.eval(script);
  assert.equal(w.__sevenMoviesGuard, state);
  w.document.body.insertAdjacentHTML('beforeend', '<ins class="adsbygoogle">Ad</ins>');
  await new Promise(resolve => setTimeout(resolve, 180));
  assert.equal(w.document.querySelector('ins.adsbygoogle'), null);
  dom.window.close();
  const player = page('https://vidlink.pro/movie/1');
  assert.equal(player.window.open('https://example.com'), null);
  assert.equal(player.window.sessionStorage.getItem('cinrift_ad_free'), null);
  player.window.close();
  const unrelated = page('https://example.org');
  assert.equal(unrelated.window.__sevenMoviesGuard, undefined);
  unrelated.window.close();
  console.log('Passed: preference, popup and link blocking, fetch/XHR/resource filtering, hostname boundary, mutation cleanup, content preservation, frame-origin scope and duplicate injection.');
})().catch(error => { console.error(error); process.exitCode = 1; });
